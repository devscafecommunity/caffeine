#!/usr/bin/env python3
"""Prints the Micromesh benchmark set (benchmarks.json, written by the env-gated Rust test
`micromesh_benchmark_set`, see scripts/benchmark-micromesh.sh) as Markdown tables.

Triangle and draw counts are exact and reproducible (the content is generated by hashes, the camera path is fixed).
`wall` is the time of a whole frame including the read-back of the 640x360 picture: it follows the GPU but also the
machine, so compare configurations of one run, not numbers between machines. `encode` is CPU command recording time.
"""
import json
import statistics as st
import sys
from pathlib import Path


def summary(values, fmt):
    return " / ".join(fmt.format(v) for v in (min(values), st.median(values), max(values)))


def main(src):
    data = json.loads((Path(src) / "benchmarks.json").read_text())
    print(f"{data['resolution'][0]}x{data['resolution'][1]}, {data['frames']} frames per flight, sun shadows on\n")
    for scene in data["scenes"]:
        print(f"### {scene['name']}\n")
        print(f"{scene['description']}; {scene['sourceTriangles']:,} source triangles.\n")
        print("| configuration | triangles (min / median / max) | draw calls | wall ms | encode ms |")
        print("|---|---|---|---|---|")
        medians = {}
        for config in scene["configs"]:
            frames = config["frames"]
            micro = any(f["microDraws"] for f in frames)
            # With Micromesh the renderer's triangle counter does not see the cut: use the cut's own count (the
            # camera's) plus what the plain draws still submit.
            triangles = [f["triangles"] + (f["microTriangles"] if micro else 0) for f in frames]
            draws = [f["drawCalls"] for f in frames]
            wall = [f["wallMs"] for f in frames]
            cpu = [f["cpuMs"] for f in frames]
            medians[config["name"]] = (st.median(triangles), st.median(wall))
            print(f"| {config['name']} | {summary(triangles, '{:,.0f}')} | {summary(draws, '{:.0f}')} | "
                  f"{summary(wall, '{:.1f}')} | {summary(cpu, '{:.1f}')} |")
        names = list(medians)
        if len(names) == 2 and names[1] == "Micromesh" and medians[names[1]][0] > 0:
            tri = medians[names[0]][0] / medians[names[1]][0]
            wall = medians[names[1]][1] / medians[names[0]][1]
            print(f"\n{names[1]} against {names[0]}: {tri:.1f}x fewer triangles, median wall time {wall:.2f} of the plain's.")
        print()


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
